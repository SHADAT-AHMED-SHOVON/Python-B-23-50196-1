import numpy as np

arr1 = np.array([2, 4, 7, 11])
arr2 = np.array([1, 3, 6, 10])

print("Summation of arr1:")
print(np.sum(arr1))

print("Product of arr1:")
print(np.prod(arr1))

print("Difference between consecutive elements of arr1:")
print(np.diff(arr1))

print("Summation of arr2:")
print(np.sum(arr2))

print("Product of arr2:")
print(np.prod(arr2))

print("Difference between consecutive elements of arr2:")
print(np.diff(arr2))